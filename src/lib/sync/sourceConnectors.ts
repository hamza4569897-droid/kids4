/**
 * Fetches discovered app candidates from a given trusted source.
 */
export async function fetchCandidatesFromSource(
  source: TrustedSource
): Promise<DiscoveredAppRawMetadata[]> {
  if (!source.is_active) {
    return [];
  }

  const connector = CONNECTORS_REGISTRY[source.id];
  if (connector && connector.isActive) {
    return await connector.fetchMetadata();
  }

  return [];
}
